class TestTruncation(unittest.TestCase):
    def test_oversize_range_is_bounded_with_explicit_count(self):
        e = _Env(self)
        for i in range(10):
            _commit(e.repo, "f%d.txt" % i, "commit number %d" % i, ["x" * 300])
        head = _git(["rev-parse", "HEAD"], e.repo)
        r = _call_build_ship_pr_body(e.repo, head, {"CLAGENTIC_SHIP_COMMITS_MAX_CHARS": "1500"})
        self.assertEqual(r.returncode, 0, r.stderr)
        section = _section_one(r.stdout)
        shown = len(re.findall(r"^- commit number \d+ \(", section, re.M))
        m = re.search(r"_(\d+) more commits not shown", section)
        self.assertIsNotNone(m, "truncation must be explicit, never silent")
        self.assertGreater(shown, 0)
        self.assertEqual(shown + int(m.group(1)), 10)
        self.assertLessEqual(len(section), 1500 + 300)
        self.assertIn("commit number 0 (", section, "oldest commits are the ones kept")

    def test_single_oversize_commit_body_is_cut_by_lines_with_count(self):
        e = _Env(self)
        _commit(e.repo, "big.txt", "huge commit", ["line %d %s" % (i, "y" * 40) for i in range(200)])
        head = _git(["rev-parse", "HEAD"], e.repo)
        r = _call_build_ship_pr_body(e.repo, head, {"CLAGENTIC_SHIP_COMMITS_MAX_CHARS": "1000"})
        section = _section_one(r.stdout)
        self.assertIn("huge commit", section)
        self.assertRegex(section, r"\[commit body truncated: \d+ more lines not shown\]")
        self.assertLessEqual(len(section), 1000 + 300)


class TestShipEndToEnd(unittest.TestCase):
    def test_created_body_captured_by_stub_contains_commit_text(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        r = e.ship()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        created = e.state()["created_bodies"]
        self.assertEqual(len(created), 1)
        for subject, body in THREE_COMMITS:
            self.assertIn(subject, created[0])
            for line in body:
                if line:
                    self.assertIn(line, created[0])
        self.assertEqual(MARKER_RE.findall(created[0]), [_git(["rev-parse", "HEAD"], e.repo)])
        self.assertEqual(e.state()["comments"], [], "a fresh PR gets a body, not a comment")

    def test_reship_with_new_commit_posts_one_comment_and_never_edits_body(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        self.assertEqual(e.ship().returncode, 0)
        original_body = e.state()["body"]
        e.set_state(calls=[])

        _commit(e.repo, "f9.txt", "fix off-by-one in parser", ["Found while reviewing."])
        new_head = _git(["rev-parse", "HEAD"], e.repo)
        r = e.ship()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

        calls = e.calls()
        self.assertEqual([c for c in calls if c.startswith("pr create")], [])
        self.assertEqual(len([c for c in calls if c.startswith("pr comment")]), 1, calls)
        for c in calls:
            self.assertFalse(c.startswith("pr edit"), "no code path may edit a PR body: %r" % c)
            self.assertFalse(c.startswith("api"), c)
            if not c.startswith("pr comment"):
                self.assertNotIn("--body", c)
        st = e.state()
        self.assertEqual(st["body"], original_body, "body must be untouched on re-ship")
        comment = st["comments"][0]
        self.assertIn("fix off-by-one in parser", comment)
        self.assertIn("Found while reviewing.", comment)
        for subject, _ in THREE_COMMITS:
            self.assertNotIn(subject, comment, "only post-marker commits belong in the delta")
        self.assertEqual(MARKER_RE.findall(comment), [new_head])

    def test_reship_with_no_new_commits_posts_nothing(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        self.assertEqual(e.ship().returncode, 0)
        e.set_state(calls=[])
        r = e.ship()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertEqual([c for c in e.calls() if c.startswith("pr comment")], [])
        self.assertEqual(e.state()["comments"], [])

    def test_third_ship_anchors_on_the_newest_marker_in_a_comment(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        self.assertEqual(e.ship().returncode, 0)
        _commit(e.repo, "g1.txt", "second wave one")
        self.assertEqual(e.ship().returncode, 0)
        _commit(e.repo, "g2.txt", "third wave two")
        self.assertEqual(e.ship().returncode, 0)
        comments = e.state()["comments"]
        self.assertEqual(len(comments), 2)
        self.assertIn("third wave two", comments[1])
        self.assertNotIn("second wave one", comments[1])

    def test_rewritten_history_posts_full_list_with_reason(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        self.assertEqual(e.ship().returncode, 0)
        _git(["commit", "-q", "--amend", "-m", "document widget flag (reworded)"], e.repo)
        _git(["push", "-q", "-f", "origin", "feat/example"], e.repo)
        e.set_state(calls=[])
        r = e.ship()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        comments = e.state()["comments"]
        self.assertEqual(len(comments), 1)
        self.assertIn("History was rewritten", comments[0])
        for subject, _ in THREE_COMMITS[:2]:
            self.assertIn(subject, comments[0])
        self.assertIn("document widget flag (reworded)", comments[0])

    def test_pr_without_a_marker_gets_full_list_with_reason(self):
        e = _Env(self)
        _add_three_commits(e.repo)
        e.set_state(exists=True, body="hand-written description, no marker")
        r = e.ship()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
