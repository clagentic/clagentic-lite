_GIT_ENV = {
    "GIT_AUTHOR_NAME": "test", "GIT_AUTHOR_EMAIL": "test@example.com",
    "GIT_COMMITTER_NAME": "test", "GIT_COMMITTER_EMAIL": "test@example.com",
}

MARKER_RE = re.compile(r"<!-- clagentic-lite:shipped-head=([0-9a-f]{40,64}) -->")
BODY_HEADING = "## What changed and why"
NEXT_HEADING = "## Review provenance"


def _git(args, cwd):
    env = {**os.environ, **_GIT_ENV}
    return subprocess.run(["git"] + args, cwd=cwd, env=env, check=True,
                          capture_output=True, text=True, timeout=60).stdout.strip()


def _commit(repo, name, subject, body_lines=None):
    path = os.path.join(repo, name)
    with open(path, "a") as f:
        f.write("%s\n" % subject)
    _git(["add", name], repo)
    args = ["commit", "-q", "-m", subject]
    if body_lines:
        args += ["-m", "\n".join(body_lines)]
    _git(args, repo)
    return _git(["rev-parse", "HEAD"], repo)


def _make_repo(tmp, with_remote=True):
    """A repo on feat/example, one seed commit on main. With a remote: a
    local bare origin that already has main, so origin/main resolves."""
    repo = os.path.join(tmp, "repo")
    subprocess.run(["git", "init", "-q", "-b", "main", repo], check=True, timeout=60)
    _commit(repo, "seed.txt", "seed")
    if with_remote:
        bare = os.path.join(tmp, "origin.git")
        subprocess.run(["git", "init", "-q", "--bare", "-b", "main", bare], check=True, timeout=60)
        _git(["remote", "add", "origin", bare], repo)
        _git(["push", "-q", "origin", "main"], repo)
    _git(["checkout", "-q", "-b", "feat/example"], repo)
    return repo


THREE_COMMITS = [
    ("add parser", ["Parses the widget format.", "Handles empty input explicitly."]),
    ("wire parser into cli", ["Adds the --widget flag.", "", "Second paragraph of the body."]),
    ("document widget flag", ["## not a real heading, just body text", "Co-Authored-By: Someone <s@example.com>"]),
]


def _add_three_commits(repo):
    for i, (subject, body) in enumerate(THREE_COMMITS):
        _commit(repo, "f%d.txt" % i, subject, body)


def _call_build_ship_pr_body(repo, head, env_extra=None):
    env = os.environ.copy()
    env.update(source_env(gates=True))
    env["CLAGENTIC_PROJECT_ROOT"] = repo
    if env_extra:
        env.update(env_extra)
    script = ". '%s'\n_build_ship_pr_body 'feat/example' '%s'\n" % (GATES_SH, head)
    return subprocess.run(["sh", "-c", script, GATES_SH], capture_output=True, text=True,
                          env=env, cwd=repo, timeout=60)


def _section_one(body):
    start = body.index(BODY_HEADING) + len(BODY_HEADING)
    return body[start:body.index(NEXT_HEADING)]


def _sweep_for_pr_body_edits(root):
    """Return (tracked shell paths, [(path, line_no)] body-edit hits). Paths
    are repo-relative exactly as ls-files prints them and are opened under
    root as-is, so a script in a subdirectory is read, not skipped."""
    tracked = subprocess.run(["git", "-C", root, "ls-files", "*.sh"],
                             capture_output=True, text=True, check=True, timeout=30).stdout.split()
    hits = []
    for rel in tracked:
        with open(os.path.join(root, rel), encoding="utf-8") as f:
            lines = f.read().splitlines()
        for n, logical in _logical_lines(lines):
            if _line_edits_pr_body(logical):
                hits.append((rel, n))
    return tracked, hits


def _logical_lines(lines):
    """Yield (first_line_no, text) with backslash continuations joined and
    comment lines dropped, so `... api path \\` + `-X PATCH` is one line."""
    out, buf, start = [], "", 0
    for n, raw in enumerate(lines, 1):
        if not buf and raw.strip().startswith("#"):
            continue
        if not buf:
            start = n
        if raw.rstrip().endswith("\\"):
            buf += raw.rstrip()[:-1] + " "
            continue
        out.append((start, buf + raw))
        buf = ""
    if buf:
        out.append((start, buf))
    return out


_API_WORD = re.compile(r"\bapi\b")
_WRITE_VERB = re.compile(r"(?i:\bPATCH\b|\bPUT\b)|(?:^|\s)-X\s*\w*|--method\b")


def _line_edits_pr_body(line):
    """True for any shape that could rewrite a PR body: `pr edit` through any
    binary, a literal `gh api`, or an `api` subcommand through a variable- or
    path-named binary combined with PATCH/PUT, -X or --method."""
    if re.search(r"\bpr\s+edit\b", line) or re.search(r"\bgh\s+api\b", line):
        return True
    return bool(_API_WORD.search(line) and _WRITE_VERB.search(line))


_FAKE_GH = textwrap.dedent('''\
    #!/usr/bin/env python3
    import json, os, sys

    state_path = os.environ["FAKE_GH_STATE"]
    argv = sys.argv[1:]
    with open(state_path) as f:
        st = json.load(f)
    st["calls"].append(argv)

    def save():
        with open(state_path, "w") as f:
            json.dump(st, f)

    def body_file():
        with open(argv[argv.index("--body-file") + 1]) as f:
            return f.read()

    OPEN_NUMBER, CLOSED_NUMBER = "7", "3"

    def target_is_closed():
        # A numeric ref addresses exactly one PR. A bare branch name is
        # ambiguous when a closed and an open PR share it; the stub resolves
        # it to the CLOSED one, the wrong-PR hazard being guarded against.
        ref = argv[2]
        if ref == CLOSED_NUMBER:
            return True
        if ref == OPEN_NUMBER:
            return False
        return bool(st.get("closed_pr"))

    rc = 0
    if argv[:2] == ["pr", "view"] and "--json" in argv:
        if st.get("read_fail"):
            sys.stderr.write("simulated read failure\\n")
            rc = 1
        elif target_is_closed():
            print(st.get("closed_body", ""))
            for c in st.get("closed_comments", []):
                print(c)
        else:
            print(st["body"])
            for c in st["comments"]:
                print(c)
    elif argv[:2] == ["pr", "list"]:
        # Open-PR lookup honoring --state (default open), modelling one open
        # PR (number 7, when "exists") and one closed PR (number 3, when
        # "closed_pr") on the same branch.
        if st.get("list_fail"):
            sys.stderr.write("simulated transient host failure\\n")
            rc = 1
        else:
            wanted = argv[argv.index("--state") + 1] if "--state" in argv else "open"
            numbers = []
            if st["exists"] and wanted in ("open", "all"):
                numbers.append(OPEN_NUMBER)
            if st.get("closed_pr") and wanted in ("closed", "all"):
                numbers.append(CLOSED_NUMBER)
            if numbers:
                print(numbers[0])
    elif argv[:2] == ["pr", "view"]:
        # Bare view matches closed/merged PRs too, as the real CLI does.
        rc = 0 if (st["exists"] or st.get("closed_pr")) else 1
    elif argv[:2] == ["pr", "create"]:
        st["exists"] = True
        st["body"] = body_file() if "--body-file" in argv else ""
        st["created_bodies"].append(st["body"])
    elif argv[:2] == ["pr", "comment"]:
        key = "closed_comments" if target_is_closed() else "comments"
        st.setdefault(key, []).append(body_file())
    save()
    sys.exit(rc)
''')


class _Env:
    """Temp dir + repo + stub gh + audit db, torn down by the test."""

    def __init__(self, test, with_remote=True):
        self.tmp = tempfile.mkdtemp(prefix="clagentic-test-ship-commits-")
        test.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.repo = _make_repo(self.tmp, with_remote=with_remote)
        self.bin = os.path.join(self.tmp, "bin")
        os.makedirs(self.bin)
        gh = os.path.join(self.bin, "gh")
        with open(gh, "w") as f:
            f.write(_FAKE_GH)
        os.chmod(gh, stat.S_IRWXU)
        self.state_path = os.path.join(self.tmp, "gh-state.json")
        self.set_state(exists=False, body="", comments=[], calls=[], created_bodies=[],
                       read_fail=False, list_fail=False, closed_pr=False)

    def set_state(self, **kw):
        st = self.state() if os.path.exists(self.state_path) else {}
        st.update(kw)
        with open(self.state_path, "w") as f:
            json.dump(st, f)

    def state(self):
        with open(self.state_path) as f:
            return json.load(f)

    def ship(self):
        env = os.environ.copy()
        env.update({
            "CLAGENTIC_PROJECT_ROOT": self.repo,
            "CLAGENTIC_GATES": "none",
            "CLAGENTIC_REPO_HOST": "github",
            "FAKE_GH_STATE": self.state_path,
            "HOME": self.tmp,
            "PATH": self.bin + os.pathsep + env.get("PATH", ""),
        })
        r = subprocess.run(["sh", GATES_SH, "ship"], cwd=self.repo, env=env,
                           capture_output=True, text=True, timeout=180)
        return r

    def calls(self):
        return [" ".join(c) for c in self.state()["calls"]]

    def audit_rows(self, gate):
        db = os.path.join(self.repo, ".clagentic", "lite", "audit.db")
        conn = sqlite3.connect(db)
        try:
            return conn.execute("SELECT outcome, details FROM gate_runs WHERE gate=?", (gate,)).fetchall()
        finally:
            conn.close()


